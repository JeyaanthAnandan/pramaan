"""Generate the fictional supplier pack: documents a rod supplier sends *after* the exporter asks
(the Precursor Lever loop). Rendered and photographed exactly like demo/generate_docs.py, but kept
out of the 24-document sample and the extraction eval set.

    backend/.venv/bin/python demo/generate_supplier_pack.py

Writes demo/supplier/*.jpg and demo/supplier/ground_truth.json (same format as the sample's).
Values: Indus Stainless Rods (SAMPLE) reports the stainless rod of EC Guidance 5d Example 2
(SEE 1.783) with the SEFA of Example 3 / Table 4-14 (0.919), the figures the what-if already uses.
"""

from __future__ import annotations

import json
import sys
from decimal import Decimal as D
from pathlib import Path

import cv2

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import factory as F  # noqa: E402
import generate_docs as G  # noqa: E402

OUT = HERE / "supplier"

ISR_STATEMENT = {
    "supplier": "ISR",
    "doc_no": "ISR-CBAM-2026-03",
    "period": "01-01-2026 to 30-09-2026",
    "see": D("1.783"),
    "sefa": D("0.919"),
    "route": "EAF + AOD (D)",
    "reducing_agent": "Electricity (EAF), ferrochrome",
    "scrap_per_t": D("0.78"),
    "pre_consumer_pct": D("40"),
    "verification_ref": "KA-VR-2026-0233",
    "verification_date": "2026-10-08",
    "opinion": "Reasonable assurance - verified without material misstatement",
    "carbon_price_paid": "None",
}


def items() -> list[dict]:
    st = ISR_STATEMENT
    ctx = dict(
        supplier=F.ROD_SUPPLIERS["ISR"], company=F.COMPANY, st=st, verifier=F.VERIFIER, st_cn="7221 00 10",
        see_s=f"{st['see']:.3f}", sefa_s=f"{st['sefa']:.3f}", scrap_s=f"{st['scrap_per_t']:.2f}", pre_s=str(st["pre_consumer_pct"]),
        proc="P2", mark="IS", mark_color="#1f4e8c", product_desc="Wire rod, stainless steel (AISI 304)", issue_date="09-10-2026",
    )
    return [{"doc_id": "stmt-ISR-2026", "doc_type": "supplier_emissions_statement", "template": "supplier_statement.html.j2", "ctx": ctx,
             "languages": ["en"], "period": ["2026-01-01", "2026-09-30"], "title": "Supplier emissions statement (Indus Stainless Rods)"}]


def main() -> int:
    rendered = G.render_all(items())
    OUT.mkdir(exist_ok=True)
    truth = []
    for n, it in enumerate(rendered):
        img, fields = G.augment(it, seed=5000 + n)
        fname = f"{it['doc_id']}.jpg"
        cv2.imwrite(str(OUT / fname), img, [cv2.IMWRITE_JPEG_QUALITY, 74])
        truth.append({
            "doc_id": it["doc_id"], "file": f"supplier/{fname}", "doc_type": it["doc_type"], "title": it["title"],
            "languages": it["languages"], "period": it["period"], "width": int(img.shape[1]), "height": int(img.shape[0]),
            "fields": fields,
        })
        print(f"{fname:30s} {it['doc_type']:30s} fields={len(fields)}")
    meta = {"note": "SAMPLE - FICTIONAL supplier pack (sent after the exporter's request). Generated by demo/generate_supplier_pack.py.",
            "box_format": "[ymin, xmin, ymax, xmax] normalised 0-1000 on the final JPEG", "documents": truth}
    (OUT / "ground_truth.json").write_text(json.dumps(meta, indent=1, ensure_ascii=False) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
